// Generates src/vocabulary.ts: every word that can appear in a date, time,
// number or currency amount formatted in one of the locales Excel ships in,
// according to Unicode CLDR (via Intl).
//
// CLDR spellings change between releases (e.g. Finnish "tammik." became
// "tammi"), so the output is the UNION of the existing file and what the
// current runtime produces. Run it with every runtime you can, e.g.:
//   node scripts/generate-vocabulary.mjs && bun scripts/generate-vocabulary.mjs
// (Pass --reset to start from scratch.)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const OUTPUT = new URL('../src/vocabulary.ts', import.meta.url);

const LOCALES = [
  'ar', 'bg', 'ca', 'cs', 'cy', 'da', 'de', 'de-AT', 'de-CH', 'el', 'en', 'en-GB', 'en-IN', 'es', 'es-MX', 'et', 'eu',
  'fa', 'fi', 'fil', 'fr', 'fr-CA', 'ga', 'gl', 'he', 'hi', 'hr', 'hu', 'id', 'is', 'it', 'ja', 'kk', 'ko', 'lt',
  'lv', 'mk', 'ms', 'mt', 'nb', 'nl', 'nn', 'pl', 'pt', 'pt-PT', 'ro', 'ru', 'sk', 'sl', 'sq', 'sr', 'sr-Latn', 'sv',
  'th', 'tr', 'uk', 'ur', 'vi', 'zh', 'zh-Hant', 'zh-HK',
];

const WORD = /[\p{L}\p{M}]+/gu;
const OTHER = /[^\p{L}\p{M}\p{Nd}]/gu;
const words = new Set();
const punctuation = new Set();
if (!process.argv.includes('--reset') && existsSync(OUTPUT)) {
  const previous = readFileSync(OUTPUT, 'utf8');
  for (const word of JSON.parse(/CLDR_WORDS = (".*");/.exec(previous)[1]).split(' ')) words.add(word);
  for (const [, hex] of /CLDR_PUNCTUATION = '(.*)';/.exec(previous)[1].matchAll(/\\u([0-9a-f]{4})/g)) {
    punctuation.add(String.fromCharCode(Number.parseInt(hex, 16)));
  }
}
const add = (text) => {
  const normalized = text.normalize('NFKC').toLowerCase();
  for (const match of normalized.matchAll(WORD)) words.add(match[0]);
  for (const match of normalized.matchAll(OTHER)) punctuation.add(match[0]);
};

const dates = [];
for (let month = 0; month < 12; month++) {
  for (const day of [1, 3, 5, 6, 7, 8, 9]) dates.push(new Date(Date.UTC(2024, month, day, 1, 5, 9)));
  dates.push(new Date(Date.UTC(2024, month, 15, 13, 5, 9)));
}
// Every hour, so all (flexible) day periods such as "晚上" or "in the evening" are covered.
for (let hour = 0; hour < 24; hour++) dates.push(new Date(Date.UTC(2024, 0, 15, hour, 30)));

const DATE_STYLES = [
  { dateStyle: 'full' }, { dateStyle: 'long' }, { dateStyle: 'medium' }, { dateStyle: 'short' },
  { timeStyle: 'short' }, { timeStyle: 'medium' }, { dateStyle: 'medium', timeStyle: 'short' },
  { month: 'long' }, { month: 'short' }, { month: 'long', day: 'numeric' }, { month: 'short', day: 'numeric' },
  { month: 'long', year: 'numeric' }, { month: 'short', year: 'numeric' }, { year: 'numeric', month: '2-digit' },
  { weekday: 'long' }, { weekday: 'short' }, { weekday: 'short', day: 'numeric', month: 'short' },
  { hour: 'numeric', hour12: true }, { hour: 'numeric', minute: '2-digit', hour12: true },
  { hour: 'numeric', minute: '2-digit', hour12: false },
  { hour: 'numeric', dayPeriod: 'narrow' }, { hour: 'numeric', dayPeriod: 'short' }, { hour: 'numeric', dayPeriod: 'long' },
];

const CURRENCIES = Intl.supportedValuesOf('currency');
for (const code of CURRENCIES) add(code);

for (const locale of LOCALES) {
  for (const style of DATE_STYLES) {
    // Both the locale's default calendar and numbering system, and Gregorian with Latin digits.
    for (const extra of [{}, { calendar: 'gregory', numberingSystem: 'latn' }]) {
      const format = new Intl.DateTimeFormat(locale, { ...style, ...extra, timeZone: 'UTC' });
      for (const date of dates) add(format.format(date));
    }
  }
  for (const currency of CURRENCIES) {
    for (const currencyDisplay of ['symbol', 'narrowSymbol', 'code']) {
      add(new Intl.NumberFormat(locale, { style: 'currency', currency, currencyDisplay }).format(-1234.5));
    }
  }
  for (const style of [{}, { style: 'percent' }, { notation: 'scientific' }, { notation: 'engineering' }]) {
    add(new Intl.NumberFormat(locale, style).format(-1234.5));
  }
}

const sorted = [...words].sort();
const symbols = [...punctuation].sort();
const escape = (char) => `\\u${char.codePointAt(0).toString(16).padStart(4, '0')}`;
const source = `// Generated by scripts/generate-vocabulary.mjs from Unicode CLDR data (via Intl). Do not edit.
// ${LOCALES.length} locales, ${sorted.length} words, ${symbols.length} symbols.

/** Words that occur in dates, times and currency amounts formatted in Excel's locales, lower-cased and NFKC-normalized. */
export const CLDR_WORDS = ${JSON.stringify(sorted.join(' '))};

/** Every non-letter, non-digit character in those formatted values, as a RegExp character class body. */
export const CLDR_PUNCTUATION = '${symbols.map(escape).join('')}';
`;
writeFileSync(OUTPUT, source);
console.log(`CLDR ${typeof Bun === 'undefined' ? process.versions.cldr : `(bun ${Bun.version})`}: ${sorted.length} words, ${symbols.length} symbols, ${source.length} bytes`);
